"""
test_write_results.py — Calls the real write_results() from backtest.py
directly (not a copy, not a description of it) across all four
availability scenarios, and checks the ACTUAL files it writes -- valid
JSON, a loadable JS const, and the right plain-language note for each case.

Doesn't touch backtest_track_b()/backtest_track_a()/evaluate_track_b()/
evaluate_track_a() at all -- those are the already-validated logic (per the
module's own docstring, checked against test_backtest.py's synthetic
fixtures) and nothing here modifies them; this only tests the NEW code.
"""
import sys
import os
import json
import tempfile
import shutil
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import backtest


def run_case(tmpdir, track_b, track_a):
    """Point backtest's OUT_JSON/OUT_JS at a temp dir, call the REAL
    write_results(), read back what actually landed on disk."""
    json_path = os.path.join(tmpdir, "backtest_results.json")
    js_path = os.path.join(tmpdir, "backtest_results.js")
    backtest.OUT_JSON = json_path
    backtest.OUT_JS = js_path

    backtest.write_results(track_b, track_a)

    with open(json_path) as f:
        json_content = f.read()
    with open(js_path) as f:
        js_content = f.read()
    return json_content, js_content


def main():
    checks = []
    tmpdir = tempfile.mkdtemp()
    try:
        # ---- Case 1: neither track has any log file yet (real early-season state) ----
        json1, js1 = run_case(tmpdir, {}, {})
        parsed1 = json.loads(json1)
        checks.append(("case 1: valid JSON", isinstance(parsed1, dict), True))
        checks.append(("case 1: note mentions 'No completed games'", "No completed games" in parsed1["note"], True))
        checks.append(("case 1: track_b is the real empty dict, not fabricated", parsed1["track_b"], {}))
        checks.append(("case 1: track_a is the real empty dict, not fabricated", parsed1["track_a"], {}))
        checks.append(("case 1: generated_at is present", "generated_at" in parsed1, True))
        checks.append(("case 1: JS file starts with the auto-generated comment",
                        js1.startswith("// Auto-generated by scripts/backtest.py"), True))
        checks.append(("case 1: JS declares BACKTEST_DATA as const (same pattern as the other two data files)",
                        "const BACKTEST_DATA = " in js1, True))

        # ---- Case 2: logs exist but zero games have finished yet (real early-season state) ----
        json2, _ = run_case(tmpdir, {"n_available": 0}, {"n_available": 0})
        parsed2 = json.loads(json2)
        checks.append(("case 2: note still says 'No completed games' (n_available=0 counts as unavailable)",
                        "No completed games" in parsed2["note"], True))

        # ---- Case 3: Track B has real results, Track A doesn't yet ----
        real_track_b = {
            "n_available": 12, "ats_all": {"n_bets": 12, "wins": 7, "losses": 5, "pushes": 0,
                                            "win_pct": 58.3, "roi_pct": 3.2},
        }
        json3, _ = run_case(tmpdir, real_track_b, {"n_available": 0})
        parsed3 = json.loads(json3)
        checks.append(("case 3: note correctly identifies Track B has results, A doesn't",
                        "Track B has real" in parsed3["note"] and "Track A does not yet" in parsed3["note"], True))
        checks.append(("case 3: real Track B numbers pass through unmodified",
                        parsed3["track_b"]["ats_all"]["win_pct"], 58.3))

        # ---- Case 4: both tracks have real results ----
        real_track_a = {"n_available": 40, "hit_rate": 0.225, "mean_predicted_prob": 0.21}
        json4, _ = run_case(tmpdir, real_track_b, real_track_a)
        parsed4 = json.loads(json4)
        checks.append(("case 4: note says both tracks have real results",
                        "Both tracks have real" in parsed4["note"], True))
        checks.append(("case 4: real Track A numbers pass through unmodified",
                        parsed4["track_a"]["hit_rate"], 0.225))

        # ---- numpy-type safety: the exact failure mode odds_api.json_default
        # exists to prevent (see that module's docstring) -- a dict containing
        # a real numpy int64/float64, as would actually come out of a pandas
        # aggregation, must not crash json.dump ----
        import numpy as np
        numpy_laced_track_b = {"n_available": np.int64(5), "some_rate": np.float64(0.481)}
        json5, _ = run_case(tmpdir, numpy_laced_track_b, {})
        parsed5 = json.loads(json5)  # would have thrown before reaching here if unhandled
        checks.append(("numpy.int64 in the results dict serializes without crashing", parsed5["track_b"]["n_available"], 5))
        checks.append(("numpy.float64 in the results dict serializes without crashing", parsed5["track_b"]["some_rate"], 0.481))

    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)

    print(f"{'check':80s} {'got':>10s} {'want':>10s}  ok")
    print("-" * 108)
    all_ok = True
    for name, got, want in checks:
        ok = got == want
        all_ok &= ok
        print(f"{name:80s} {str(got):>10s} {str(want):>10s}  {'PASS' if ok else 'FAIL'}")
    print("-" * 108)
    print("ALL PASS" if all_ok else "SOME FAILED")
    return 0 if all_ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
